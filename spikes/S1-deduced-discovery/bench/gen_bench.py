#!/usr/bin/env python3
"""Generate the arity-probing benchmark: N classes with 0..8 constructor parameters.

usage: gen_bench.py VARIANT N OUT.cpp

Class i has arity i % 9 (so 100 classes give 11 or 12 of each arity 0..8).
Its parameters cycle through six request forms over ten empty dependency types.

Variants (each translation unit differs only in what it asserts per class):
  baseline   the classes alone
  explicit   std::is_constructible<C, declared parameter types...>, the cost of
             checking an explicit ctor_traits declaration
  search     s1::search_arity<C>() == arity (just the arity search)
  discover   s1::ctor_info<C>::arity == arity (abstract check, search, greedy
             check, shorter-arity check: the full discovery)
The search strategy and the limit come from -DS1_SEARCH and -DS1_MAX_ARITY.
"""
import sys

FORMS = ["d{k}", "const d{k}&", "d{k}&", "d{k}*", "std::unique_ptr<d{k}>", "std::shared_ptr<d{k}>"]


def params(i):
    arity = i % 9
    return [FORMS[(i + j) % len(FORMS)].format(k=(i * 7 + j * 3) % 10) for j in range(arity)]


def main():
    variant, n, out = sys.argv[1], int(sys.argv[2]), sys.argv[3]
    lines = ["// generated by gen_bench.py; do not edit", "#include <memory>", "#include <type_traits>"]
    if variant in ("search", "discover"):
        lines.append('#include "deduce.hpp"')
    lines += [f"struct d{k} {{}};" for k in range(10)]
    for i in range(n):
        ps = params(i)
        args = ", ".join(f"{p} a{j}" for j, p in enumerate(ps))
        lines.append(f"struct c{i} {{ c{i}({args}) {{}} }};")
    for i in range(n):
        ps = params(i)
        if variant == "explicit":
            lines.append(f"static_assert(std::is_constructible_v<c{i}{''.join(', ' + p for p in ps)}>);")
        elif variant == "search":
            lines.append(f"static_assert(s1::search_arity<c{i}>() == {len(ps)});")
        elif variant == "discover":
            lines.append(f"static_assert(s1::ctor_info<c{i}>::arity == {len(ps)});")
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
